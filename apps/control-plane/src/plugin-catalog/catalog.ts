import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { Controller, Get, Injectable, Module, Param } from "@nestjs/common";
import { RequiredRole } from "../auth/auth.js";
import { notFound } from "../common/problem.js";
import { PACKAGE_ROOT } from "../config.js";

export interface PluginCatalogEntry {
  name: string;
  category: string;
  source: "bundled" | "custom";
  supportedInDbless: boolean;
}

interface Catalog {
  kongVersion: string;
  items: PluginCatalogEntry[];
}

/** What the API shows (and accepts back, meaning "keep the stored value") in place of a plugin secret. */
export const SECRET_PLACEHOLDER = "REDACTED";

/** Generated by `pnpm --filter @gromesh/control-plane catalog:generate` from the reference Kong. */
const CATALOG_DIR = resolve(PACKAGE_ROOT, "src/plugin-catalog/kong-3.9");

@Injectable()
export class PluginCatalog {
  private catalog: Catalog | null = null;
  private readonly schemas = new Map<string, unknown>();
  private readonly secrets = new Map<string, string[][]>();

  list(): Catalog {
    this.catalog ??= JSON.parse(readFileSync(resolve(CATALOG_DIR, "_catalog.json"), "utf8")) as Catalog;
    return this.catalog;
  }

  find(name: string): PluginCatalogEntry | undefined {
    return this.list().items.find((p) => p.name === name);
  }

  schema(name: string): unknown {
    // Only names from the catalog reach the filesystem.
    if (!this.find(name)) throw notFound("Plugin schema");
    if (!this.schemas.has(name)) this.schemas.set(name, JSON.parse(readFileSync(resolve(CATALOG_DIR, `${name}.json`), "utf8")));
    return this.schemas.get(name);
  }

  defaultProtocols(name: string): string[] | undefined {
    if (!this.find(name)) return undefined;
    const schema = this.schema(name) as { fields: Record<string, { default?: string[] }>[] };
    return schema.fields.find(f => f.protocols)?.protocols?.default;
  }

  /**
   * Copy of `config` with every field Kong marks `encrypted` (passwords, API keys, secrets) set to "REDACTED".
   * Used wherever a plugin config leaves the control plane (API responses, audit, publish-preview, snapshot diff):
   * secrets are write-only, only the snapshot handed to the agent carries them.
   */
  redactConfig(name: string, config: Record<string, unknown>): Record<string, unknown> {
    let out = config;
    for (const path of this.secretPaths(name)) out = redactPath(out, path);
    return out;
  }

  /**
   * Resolves the "REDACTED" placeholders of an incoming config: each one takes the secret stored in `current`
   * (the plugin being replaced). Returns the config paths where there was nothing to keep.
   */
  mergeSecrets(name: string, incoming: Record<string, unknown>, current: Record<string, unknown> | null): { config: Record<string, unknown>; missing: string[] } {
    let config = incoming;
    const missing: string[] = [];
    for (const path of this.secretPaths(name)) {
      if (valueAt(incoming, path) !== SECRET_PLACEHOLDER) continue;
      const kept = current ? valueAt(current, path) : undefined;
      if (kept === undefined || kept === null || kept === SECRET_PLACEHOLDER) missing.push(["config", ...path].join("."));
      else config = setPath(config, path, kept);
    }
    return { config, missing };
  }

  /** Import replaces non-secret attributes, but omission may preserve an existing encrypted slot. */
  preserveImportSecrets(name: string, incoming: Record<string, unknown>, current: Record<string, unknown> | null) {
    let config = structuredClone(incoming);
    for (const path of this.secretPaths(name)) {
      const value = current ? valueAt(current, path) : undefined;
      if (valueAt(config, path) !== undefined || typeof value !== "string") continue;
      let target = config;
      for (const key of path.slice(0, -1)) {
        if (!isRecord(target[key])) target[key] = {};
        target = target[key] as Record<string, unknown>;
      }
      target[path.at(-1)!] = value;
    }
    return this.mergeSecrets(name, config, current);
  }

  /** The pinned schema is also the allow-list: Kong may accept fields our pinned model does not know. */
  importConfigErrors(name: string, config: Record<string, unknown>): { path: string; message: string }[] {
    if (!this.find(name)) return [];
    type Def = { fields?: Record<string, Def>[]; elements?: Def; type?: string };
    const schema = this.schema(name) as Def;
    const definition = schema.fields?.find(f => f.config)?.config;
    const errors: { path: string; message: string }[] = [];
    const walk = (value: unknown, def: Def | undefined, path: string) => {
      if (isRecord(value) && def?.fields) {
        const fields = Object.assign({}, ...def.fields) as Record<string, Def>;
        for (const [key, child] of Object.entries(value)) {
          if (!Object.hasOwn(fields, key)) errors.push({ path: `${path}.${key}`, message: "unknown plugin config field" });
          else walk(child, fields[key], `${path}.${key}`);
        }
      } else if (Array.isArray(value) && def?.elements) value.forEach((child, i) => walk(child, def.elements, `${path}.${i}`));
    };
    walk(config, definition, "config");
    return errors;
  }

  /** Copy of `config` with every string at a secret path replaced by `fn(value)` (seal or open at rest). */
  mapSecrets(name: string, config: Record<string, unknown>, fn: (value: string, path: string[]) => string): Record<string, unknown> {
    let out = config;
    for (const path of this.secretPaths(name)) {
      const current = valueAt(out, path);
      if (typeof current === "string" && current !== SECRET_PLACEHOLDER) out = setPath(out, path, fn(current, path));
    }
    return out;
  }

  /** Paths of the `encrypted` fields, relative to `config`, for a plugin of the catalog (none for unknown names). */
  private secretPaths(name: string): string[][] {
    if (!this.find(name)) return [];
    let paths = this.secrets.get(name);
    if (!paths) {
      const all: string[][] = [];
      collectSecrets((this.schema(name) as { fields: SchemaField[] }).fields, [], all);
      // Kong paths start at the entity: ["config", "redis", "password"].
      paths = all.filter((p) => p[0] === "config").map((p) => p.slice(1));
      this.secrets.set(name, paths);
    }
    return paths;
  }
}

type SchemaField = Record<string, { type?: string; encrypted?: boolean; fields?: SchemaField[] }>;

function collectSecrets(fields: SchemaField[], prefix: string[], out: string[][]): void {
  for (const field of fields) {
    for (const [name, def] of Object.entries(field)) {
      if (def.encrypted) out.push([...prefix, name]);
      if (def.type === "record" && def.fields) collectSecrets(def.fields, [...prefix, name], out);
    }
  }
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function valueAt(obj: Record<string, unknown>, path: string[]): unknown {
  let cur: unknown = obj;
  for (const key of path) {
    if (!isRecord(cur)) return undefined;
    cur = cur[key];
  }
  return cur;
}

/** Copy of `obj` with the value at `path` replaced; a missing or non-record ancestor leaves `obj` untouched. */
function setPath(obj: Record<string, unknown>, path: string[], value: unknown): Record<string, unknown> {
  const [head, ...rest] = path;
  if (head === undefined || !(head in obj)) return obj;
  if (rest.length === 0) return { ...obj, [head]: value };
  const child = obj[head];
  return isRecord(child) ? { ...obj, [head]: setPath(child, rest, value) } : obj;
}

function redactPath(obj: Record<string, unknown>, path: string[]): Record<string, unknown> {
  const current = valueAt(obj, path);
  return current === undefined || current === null ? obj : setPath(obj, path, SECRET_PLACEHOLDER);
}

@Controller("plugin-schemas")
export class PluginCatalogController {
  constructor(private readonly catalog: PluginCatalog) {}

  @Get()
  @RequiredRole("viewer")
  list() {
    return this.catalog.list();
  }

  @Get(":pluginName")
  @RequiredRole("viewer")
  get(@Param("pluginName") name: string) {
    return this.catalog.schema(name);
  }
}

@Module({ controllers: [PluginCatalogController], providers: [PluginCatalog], exports: [PluginCatalog] })
export class PluginCatalogModule {}
